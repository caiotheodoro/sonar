/**
 * Derives repository facts from the tree into src/data/repo-facts.json.
 *
 * Same rule as the results binding: a number that can drift must not be
 * typed. The suite size and the revision the video was cut at are read from
 * the filesystem and git, so an outro that says how many tests ran cannot go
 * stale silently.
 *
 * Run before rendering: node capture/collect-repo-facts.mjs [--tests]
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const VIDEO = resolve(HERE, "..");
const REPO = resolve(VIDEO, "..");
const OUT = join(VIDEO, "src", "data", "repo-facts.json");

const testFiles = readdirSync(join(REPO, "tests")).filter((f) => /^test_.*\.py$/.test(f));
const rev = execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd: REPO, encoding: "utf8" }).trim();

const previous = existsSync(OUT) ? JSON.parse(readFileSync(OUT, "utf8")) : {};
let testsCollected = previous.testsCollected ?? null;

if (process.argv.includes("--tests")) {
  const out = execFileSync("uv", ["run", "pytest", "--collect-only", "-q"], {
    cwd: REPO,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  });
  // pytest -q prints one "path: N" line per file, not one line per test id.
  testsCollected = out
    .split("\n")
    .map((l) => /^tests\/.*: (\d+)$/.exec(l.trim()))
    .filter(Boolean)
    .reduce((a, m) => a + Number(m[1]), 0);
}

const facts = {
  _comment: "Generated by capture/collect-repo-facts.mjs. Do not edit by hand; re-run it.",
  generatedFrom: "filesystem and git",
  sonarRev: rev,
  testFiles: testFiles.length,
  testsCollected,
};

writeFileSync(OUT, `${JSON.stringify(facts, null, 2)}\n`);
console.log(
  `rev: ${facts.sonarRev} · test files: ${facts.testFiles} · tests: ${facts.testsCollected ?? "(pass --tests)"}`,
);
