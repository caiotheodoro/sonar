/**
 * Emits VOICE-SCRIPT.md from narration.json.
 *
 * The two are never kept in step by hand: generating the script makes the
 * match structural, so the file cannot drift from the cues it is built from.
 *
 * Usage: node capture/emit-voicescript.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const VIDEO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const narration = JSON.parse(readFileSync(join(VIDEO, "src", "data", "narration.json"), "utf8"));

/**
 * One paragraph per cue, a `<break>` between them: capture/measure-cues.mjs
 * finds the cues again as the silences the break leaves in the mp3. Eleven
 * Multilingual v2 honours the tag in the web UI; if a model ignores it, the
 * blank line is still a pause.
 */
export const BREAK = '<break time="0.9s" />';
export const spokenOf = (cues) => cues.map((c) => c.spoken ?? c.text).join(`\n\n${BREAK}\n\n`);

/**
 * Guarded: the write used to run on import in the pipeline this is copied
 * from, so importing `spokenOf` silently regenerated the file.
 */
const main = () => {
  const cues = narration.narration ?? [];
  const text = spokenOf(cues);
  const words = text.trim() ? text.split(/\s+/).length : 0;
  const scenes = [...new Set(cues.map((c) => c.act))];
  const voice = narration.voice ?? {};

  const body = cues.length
    ? [
        `## narration  →  \`public/narration.mp3\``,
        "",
        `*${words} words · ${text.length} chars · acts: ${scenes.join(", ")} · voice ${voice.voice ?? "?"} (${voice.voice_id ?? "?"}) · model ${voice.model ?? "?"}*`,
        "",
        "```text",
        text,
        "```",
        "",
        "---",
        "",
      ].join("\n")
    : "_No cues yet. Fill `src/data/narration.json` and re-run._\n\n---\n\n";

  const head = [
    "# Narration — one block to record",
    "",
    "Generated in the ElevenLabs web UI (Text to Speech → the voice named below → paste the block →",
    "Generate → Download), then saved as public/narration.mp3 and measured with capture/measure-cues.mjs.",
    "Library voices are 402 through the API on the free plan (docs/HANDOFF.md, W7.2), so this is a browser step.",
    "",
    "Generated by `node capture/emit-voicescript.mjs` — do not edit by hand.",
    "",
    "Every `<break>` is a real pause the cue measurer relies on. Respellings in `spoken` are",
    "deliberate; `text` is what the .srt sidecar shows.",
    "",
    "---",
    "",
  ].join("\n");

  writeFileSync(join(VIDEO, "VOICE-SCRIPT.md"), head + body + `**${text.length} characters.**\n`);
  console.log(`${cues.length} cue(s) -> VOICE-SCRIPT.md (${text.length} chars)`);
};

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
